export const MAX_PREPARED_HERO_BYTES = 8 * 1024 * 1024;
export const MAX_LOCAL_SOURCE_BYTES = 256 * 1024 * 1024;

type MediaEvidence = {
  bytes: number;
  sha256: string;
  width: number;
  height: number;
  duration: number;
  frames: number;
  frameRate: string;
  colour: string[];
  audioStreams: number;
};
export type HeroPreparationReport = {
  version: 1;
  tool: "soso-offline-hero";
  crf: number;
  before: MediaEvidence;
  after: MediaEvidence;
};

export function validatePreparationReport(value: unknown): HeroPreparationReport {
  const report = value as HeroPreparationReport | null;
  const validEvidence = (item: MediaEvidence | undefined) => item
    && Number.isSafeInteger(item.bytes) && item.bytes > 0
    && /^[a-f0-9]{64}$/.test(item.sha256)
    && Number.isSafeInteger(item.width) && item.width > 0
    && Number.isSafeInteger(item.height) && item.height > 0
    && Number.isFinite(item.duration) && item.duration > 0
    && Number.isSafeInteger(item.frames) && item.frames > 0
    && typeof item.frameRate === "string" && /^\d+\/[1-9]\d*$/.test(item.frameRate)
    && Array.isArray(item.colour) && item.colour.length === 4 && item.colour.every((entry) => typeof entry === "string")
    && Number.isSafeInteger(item.audioStreams) && item.audioStreams >= 0;
  if (!report || report.version !== 1 || report.tool !== "soso-offline-hero"
    || !Number.isInteger(report.crf) || report.crf < 18 || report.crf > 28
    || !validEvidence(report.before) || !validEvidence(report.after)) {
    throw new Error("Choose the JSON report generated by SOSO’s offline preparation tool.");
  }
  if (report.after.bytes > MAX_PREPARED_HERO_BYTES || report.after.bytes >= report.before.bytes) {
    throw new Error("Prepared video must be smaller than the source and no larger than 8 MiB.");
  }
  if (report.before.width !== report.after.width || report.before.height !== report.after.height
    || report.before.frames !== report.after.frames || report.before.frameRate !== report.after.frameRate
    || Math.abs(report.before.duration - report.after.duration) > 0.1
    || report.before.audioStreams !== report.after.audioStreams
    || JSON.stringify(report.before.colour) !== JSON.stringify(report.after.colour)) {
    throw new Error("Preparation must preserve dimensions, frames, duration and colour metadata.");
  }
  return report;
}

async function sha256(file: File) {
  const hash = await crypto.subtle.digest("SHA-256", await file.arrayBuffer());
  return Array.from(new Uint8Array(hash), (byte) => byte.toString(16).padStart(2, "0")).join("");
}

export async function verifyPreparedHero(original: File, candidate: File, reportFile: File) {
  if (original.size < 1 || original.size > MAX_LOCAL_SOURCE_BYTES) {
    throw new Error("Local source preview is limited to 256 MiB. Keep larger originals offline; create and approve a compatible reference export first.");
  }
  if (!/^[A-Za-z0-9][A-Za-z0-9._ -]{0,159}$/i.test(candidate.name) || !/\.mp4$/i.test(candidate.name)
    || candidate.type !== "video/mp4" || candidate.size < 1 || candidate.size > MAX_PREPARED_HERO_BYTES) {
    throw new Error("Prepared file must be a safely named MP4 with video/mp4 MIME, up to 8 MiB.");
  }
  if (reportFile.size > 16 * 1024) throw new Error("Preparation report must be no larger than 16 KiB.");
  const report = validatePreparationReport(JSON.parse(await reportFile.text()));
  if (report.before.bytes !== original.size || report.after.bytes !== candidate.size) {
    throw new Error("Selected files do not match the report’s before/after byte sizes.");
  }
  const header = new Uint8Array(await candidate.slice(0, 128).arrayBuffer());
  const signature = String.fromCharCode(...header);
  if (signature.slice(4, 8) !== "ftyp" || !/(isom|iso2|mp41|mp42|avc1)/.test(signature.slice(8))) {
    throw new Error("Prepared bytes are not a supported MP4 container.");
  }
  if (await sha256(original) !== report.before.sha256 || await sha256(candidate) !== report.after.sha256) {
    throw new Error("Selected files do not match the preparation report. Select the actual source and its unchanged export.");
  }
  return report;
}

export function previewMatchesEvidence(video: Pick<HTMLVideoElement, "videoWidth" | "videoHeight" | "duration">, evidence: MediaEvidence) {
  return video.videoWidth === evidence.width && video.videoHeight === evidence.height
    && Number.isFinite(video.duration) && Math.abs(video.duration - evidence.duration) <= 0.15;
}
